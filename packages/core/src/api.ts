/** Wire types shared by the server and the clients. */

export const USERNAME_RE = /^[a-z0-9_.]{3,32}$/;

export interface RegisterRequest {
  username: string;
  password: string;
  identityKey: string;
  signedPreKey: { id: number; pub: string; sig: string };
  oneTimePreKeys: { id: number; pub: string }[];
}

export interface KeyBundleResponse {
  identityKey: string;
  signedPreKey: { id: number; pub: string; sig: string };
  oneTimePreKey?: { id: number; pub: string };
}

/** Employee login with the ID + password the admin gave them. The device creates its own keys. */
export interface LoginRequest {
  username: string;
  password: string;
  /** Required on first login (and after an admin reset): the employee's own new password. */
  newPassword?: string;
  /** Random secret generated by this device; used to authenticate every later request. */
  deviceSecret: string;
  identityKey: string;
  signedPreKey: { id: number; pub: string; sig: string };
  oneTimePreKeys: { id: number; pub: string }[];
}

export const MIN_PASSWORD_LENGTH = 8;

export interface AdminUser {
  username: string;
  /** false = created by the admin but the employee has not logged in yet */
  active: boolean;
  admin: boolean;
  mustChangePassword: boolean;
}

export interface PublicConfig {
  /** false = only admins can create accounts (employees log in with credentials from the admin) */
  openRegistration: boolean;
  /** Sealed sender: base64 Ed25519 key that signs sender certificates. */
  certKey?: string;
}

export interface MeResponse {
  username: string;
  isAdmin: boolean;
  /** Who may send announcements; clients only show the 📢 badge for these senders. */
  admins: string[];
}

export interface UploadKeysRequest {
  signedPreKey?: { id: number; pub: string; sig: string };
  oneTimePreKeys?: { id: number; pub: string }[];
}

export interface IceConfigResponse {
  iceServers: { urls: string | string[]; username?: string; credential?: string }[];
  /** When a TURN server is configured, calls go only through it so peers never learn each other's IP. */
  relayOnly: boolean;
}

/** What a wake-up push says. It never contains the sender or any message content. */
export type PushKind = 'message' | 'call';

/** PUT /v1/push: this device's Firebase Cloud Messaging token (Android and iOS). */
export interface PushTokenRequest {
  token: string;
}

// ---- WebSocket frames ----
export type ClientFrame =
  | { type: 'auth'; username: string; password: string }
  | {
      type: 'send';
      ref: string;
      to: string;
      body: string;
      /** Wake the recipient with a content-free push if they are offline. Absent = no push (receipts etc.). */
      push?: PushKind;
    }
  | { type: 'ack'; id: number }
  | { type: 'ping' };

export type ServerFrame =
  | { type: 'ready'; preKeyCount: number; isAdmin?: boolean; admins?: string[] }
  | { type: 'envelope'; id: number; from: string; body: string; ts: number }
  | { type: 'sent'; ref: string; ts: number }
  | { type: 'error'; ref?: string; code: string; message: string }
  | { type: 'pong' };

// ---- decrypted payloads (only clients ever see these) ----
export type CallAction = 'offer' | 'answer' | 'ice' | 'hangup' | 'reject' | 'busy';

export type Payload =
  | { k: 'text'; id: string; text: string; ts: number; expire?: number; bc?: boolean; att?: AttachmentPointer }
  | { k: 'receipt'; ids: string[]; status: 'delivered' | 'read' }
  | { k: 'timer'; expire: number }
  | { k: 'screenshot' }
  /** Sealed sender: my delivery key, so you may send me messages without revealing yourself to the server. */
  | { k: 'dk'; key: string }
  | {
      k: 'call';
      callId: string;
      action: CallAction;
      video?: boolean;
      sdp?: string;
      candidate?: { candidate: string; sdpMid: string | null; sdpMLineIndex: number | null };
    };

export const MAX_TEXT_LENGTH = 8000;
export const MAX_ATTACHMENT_BYTES = 25 * 1024 * 1024;

/**
 * Travels INSIDE the encrypted message. The server only has the encrypted blob under `id`;
 * without `key` it is random noise. `digest` (SHA-256 of the ciphertext) detects tampering.
 */
export interface AttachmentPointer {
  id: string;
  key: string;
  digest: string;
  name: string;
  mime: string;
  size: number;
}
